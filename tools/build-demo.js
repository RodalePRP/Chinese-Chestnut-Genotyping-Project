/**
 * Regenerates assets/demo.js — the offline preview shown when assets/config.js has no API_URL.
 * It uses REAL submissions from tools/preview-data.json (currently Rodale Institute plates 001–002)
 * and real survey points from tools/preview-gps.json (DCNR North Orchard survey),
 * passed through the same Code.gs functions the live API uses, so preview and live views match.
 * Run from the repo root after changing apps-script/Code.gs or the preview data:  node tools/build-demo.js
 */
const fs = require('fs'), vm = require('vm'), path = require('path');
const root = path.join(__dirname, '..');
const ctx = { console, Utilities: { formatDate: d => d.toISOString().slice(0, 10) } };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'apps-script/Code.gs'), 'utf8'), ctx);
const run = (expr) => vm.runInContext(expr, ctx);

const trees = JSON.parse(fs.readFileSync(path.join(root, 'tools/preview-data.json'), 'utf8')).trees;
const gpsFile = path.join(root, 'tools/preview-gps.json');
const gpsRows = fs.existsSync(gpsFile) ? JSON.parse(fs.readFileSync(gpsFile, 'utf8')) : [];
const siteCols = run('SITE_COLUMNS').map(c => c[0]);
const siteRows = run('SEED_SITES').map(r => Object.fromEntries(siteCols.map((k, i) => [k, r[i]])));
const programs = run('PROGRAMS');
const counts = {};
trees.forEach(t => { const p = programs.find(x => x.label === t.program); if (p) counts[p.prefix] = (counts[p.prefix] || 0) + 1; });

const portal = run('buildPortalConfig_')(counts);
const mapData = run('assembleMapData_')(trees, siteRows, gpsRows);
const mapByRole = Object.fromEntries(['public', 'member', 'team'].map(r => [r, run('filterMapForRole_')(mapData, r)]));
const resultsByRole = Object.fromEntries(['public', 'member', 'team'].map(r => [r, run('filterResults_')([], [], trees, r)]));
const summary = run('summarize_')(trees);
const treeTable = run('publicTrees_')(trees.map((t, i) => Object.assign({ _row: i + 2 }, t)), gpsRows);

const out = `/* AUTO-GENERATED by tools/build-demo.js from tools/preview-data.json (real submissions). Do not edit by hand. */
(function () {
  var PORTAL = ${JSON.stringify(portal)};
  var MAP = ${JSON.stringify(mapByRole)};
  var RESULTS = ${JSON.stringify(resultsByRole)};
  // Preview access codes (the live site uses TEAM_ACCESS_CODE / MEMBER_ACCESS_CODE in Code.gs)
  var role = function (c) { c = String(c || '').trim().toUpperCase(); return c === 'PREVIEW-TEAM' ? 'team' : c === 'PREVIEW-MEMBER' ? 'member' : 'public'; };
  var SUMMARY = ${JSON.stringify(summary)};
  var TREES = ${JSON.stringify(treeTable)};
  var n = {}, seen = {};
  window.DEMO_API = {
    getPortalConfig: function () { return PORTAL; },
    getMapData: function (code) { return MAP[role(code)]; },
    getResults: function (code) { return RESULTS[role(code)]; },
    checkAccess: function (code) { return { role: role(code) }; },
    getSummary: function () { return SUMMARY; },
    getTrees: function () { return TREES; },
    checkExisting: function (prefix, ids) { return ids.filter(function (i) { return seen[prefix + '|' + String(i).toLowerCase()]; }); },
    submitBatch: function (p) {
      var mapping = [], skipped = [];
      p.rows.forEach(function (r) {
        var k = p.prefix + '|' + String(r.treeId).toLowerCase();
        if (seen[k] && p.skipExisting) { skipped.push(r.treeId); return; }
        seen[k] = 1; n[p.prefix] = (n[p.prefix] || 0) + 1;
        mapping.push([p.prefix + '-TEST-' + ('000' + n[p.prefix]).slice(-4), r.treeId]);
      });
      window.DEMO_LAST = p;
      return { added: mapping.length, skipped: skipped, mapping: mapping };
    },
    sendList: function (p) { window.DEMO_LAST_LIST = p; return { batchId: p.batchId, files: (p.files || []).length }; }
  };
})();
`;
fs.writeFileSync(path.join(root, 'assets/demo.js'), out);
console.log('assets/demo.js:', mapData.trees.length, 'trees,', mapData.trees.filter(t => t.lat != null).length, 'mapped,', mapData.unlinked.length, 'unsampled points,', mapData.sites.length, 'sites,', mapData.pins.length, 'pins', JSON.stringify(mapData.pins.map(p => [p.label, p.count])), '| plates used', summary.platesUsed, '| qc', JSON.stringify(treeTable.qc));
